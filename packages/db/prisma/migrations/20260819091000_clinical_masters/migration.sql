-- ---------------------------------------------------------------------------
-- At most one PRIMARY coding per (item, system).
--
-- Prisma cannot express `WHERE is_primary`. Without this a clinic can nominate
-- two different ICD-10 codes as the one to print on a report, and which one
-- appears is then whatever the planner felt like.
--
-- ⚠️ PER SYSTEM, NOT PER ITEM. One diagnosis legitimately has a primary ICD-10
--   code AND a primary SNOMED code; those are answers to different questions.
-- ---------------------------------------------------------------------------
CREATE UNIQUE INDEX "clinical_master_codings_one_primary"
  ON "clinical_master_codings" ("organization_id", "item_id", "system") NULLS NOT DISTINCT
  WHERE "is_primary";

-- ---------------------------------------------------------------------------
-- The clinical selector's search index.
--
-- ⚠️ A GIN TRIGRAM INDEX OVER AN EXPRESSION, WHICH PRISMA CAN NEITHER EXPRESS
--   NOR SEE. Because it cannot see it, it will never propose to drop it — the
--   opposite of the plain-column trigram index on `patients.phone`, which
--   Prisma DID offer to drop until it was declared in the schema.
--
--   Without it, every keystroke in every clinical selector is a sequential scan
--   over every word on the PLATFORM — filtered by RLS afterwards, so the cost
--   grows with the platform and not with the tenant. This is the exact failure
--   `patients` documented, and the selectors here are typed into far more often
--   than a patient search is.
--
-- `pg_trgm` is already installed by an earlier migration.
-- ---------------------------------------------------------------------------
CREATE INDEX "clinical_master_items_name_trgm_idx"
  ON "clinical_master_items" USING GIN (lower("name") gin_trgm_ops);

-- ---------------------------------------------------------------------------
-- RLS — platform-extensible, read permissive, write strict.
--
-- ⚠️ THIS IS THE `specialties` POLICY, NOT THE `files` POLICY, AND THE
--   DIFFERENCE IS A CROSS-TENANT WRITE. `files` permits a NULL organization_id
--   in its WITH CHECK, which is right for an asset the platform uploads on a
--   tenant's behalf. Reproducing it here would let ANY CLINIC INSERT A
--   PLATFORM-WIDE DIAGNOSIS — a row with organization_id NULL, instantly
--   visible to every other tenant on the platform, writable by anyone holding
--   `clinical.master.manage`.
--
-- The `platform_rows_immutable` trigger closes the two holes the policy cannot:
-- a DELETE of a platform row (Postgres applies no WITH CHECK to DELETE, so
-- USING is the whole test and USING permits NULL), and CAPTURE by an UPDATE
-- that sets organization_id to the caller's own. See the full reasoning in
-- `rls/enable-rls.sql`; it is not repeated here.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  t text;
  platform_extensible text[] := ARRAY[
    'clinical_master_items',
    'clinical_master_codings',
    'clinical_master_scopes',
    'product_clinical_scopes'
  ];
BEGIN
  FOREACH t IN ARRAY platform_extensible LOOP
    EXECUTE format('ALTER TABLE %I ENABLE   ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I NO FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
    EXECUTE format($f$
      CREATE POLICY tenant_isolation ON %I
        USING      (organization_id IS NULL OR organization_id = app_current_org())
        WITH CHECK (organization_id = app_current_org())
    $f$, t);

    EXECUTE format('DROP TRIGGER IF EXISTS platform_rows_immutable ON %I', t);
    EXECUTE format($f$
      CREATE TRIGGER platform_rows_immutable
        BEFORE UPDATE OR DELETE ON %I
        FOR EACH ROW EXECUTE FUNCTION refuse_platform_row_mutation()
    $f$, t);
  END LOOP;
END
$$;

-- ---------------------------------------------------------------------------
-- Both scope tables point at TWO parents and only one is composite-FK'd.
--
-- `specialty_id` is a PLAIN FK to `specialties(id)`, because a specialty may be
-- a platform row with no organization_id to compose with. `tenant_isolation`
-- therefore constrains the ITEM/PRODUCT side and says nothing at all about the
-- SPECIALTY side — without this, a tenant could scope its own diagnosis to
-- ANOTHER TENANT'S private specialty and read that specialty's name back out of
-- the join.
--
-- Identical shape and reasoning to `specialty_visible` on `doctor_specialties`.
-- RESTRICTIVE so it ANDs with tenant_isolation rather than widening it.
-- ---------------------------------------------------------------------------
DROP POLICY IF EXISTS specialty_visible ON clinical_master_scopes;
CREATE POLICY specialty_visible ON clinical_master_scopes AS RESTRICTIVE
  USING (EXISTS (
    SELECT 1 FROM specialties s
    WHERE s.id = clinical_master_scopes.specialty_id
      AND (s.organization_id IS NULL OR s.organization_id = app_current_org())
  ))
  WITH CHECK (EXISTS (
    SELECT 1 FROM specialties s
    WHERE s.id = clinical_master_scopes.specialty_id
      AND (s.organization_id IS NULL OR s.organization_id = app_current_org())
  ));

DROP POLICY IF EXISTS specialty_visible ON product_clinical_scopes;
CREATE POLICY specialty_visible ON product_clinical_scopes AS RESTRICTIVE
  USING (EXISTS (
    SELECT 1 FROM specialties s
    WHERE s.id = product_clinical_scopes.specialty_id
      AND (s.organization_id IS NULL OR s.organization_id = app_current_org())
  ))
  WITH CHECK (EXISTS (
    SELECT 1 FROM specialties s
    WHERE s.id = product_clinical_scopes.specialty_id
      AND (s.organization_id IS NULL OR s.organization_id = app_current_org())
  ));

-- ---------------------------------------------------------------------------
-- `product_clinical_scopes.product_id` is composite-FK'd to
-- `products(organization_id, id)`, so a tenant cannot cite another tenant's
-- product — but under MATCH SIMPLE that constraint is NOT CHECKED AT ALL when
-- organization_id is NULL, which is exactly the platform case. A restrictive
-- product predicate closes it, as `batches.product_visible` does.
-- ---------------------------------------------------------------------------
DROP POLICY IF EXISTS product_visible ON product_clinical_scopes;
CREATE POLICY product_visible ON product_clinical_scopes AS RESTRICTIVE
  USING (EXISTS (
    SELECT 1 FROM products p
    WHERE p.id = product_clinical_scopes.product_id
      AND (p.organization_id IS NULL OR p.organization_id = app_current_org())
  ))
  WITH CHECK (EXISTS (
    SELECT 1 FROM products p
    WHERE p.id = product_clinical_scopes.product_id
      AND (p.organization_id IS NULL OR p.organization_id = app_current_org())
  ));

