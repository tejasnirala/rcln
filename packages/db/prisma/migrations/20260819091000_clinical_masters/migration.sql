-- ---------------------------------------------------------------------------
-- NULLS NOT DISTINCT on the four BUSINESS keys.
--
-- Every one contains `organization_id`, which is NULL on a platform row. Under
-- Postgres's default NULLS DISTINCT two rows with a NULL organization_id are
-- unique against each other WHATEVER the other columns say — so the platform
-- vocabulary would not be unique against itself, and the seed's `findFirst`
-- would silently start creating duplicate diagnoses on its second run.
--
-- ⚠️ THE `(organization_id, id)` COMPOSITE-FK TARGET IS DELIBERATELY LEFT ALONE,
--   exactly as the product catalogue left its own. `id` is the primary key, so
--   that index is already unique on its own whatever NULLs the first column
--   holds — and the rewrite would FAIL anyway, because Postgres refuses to drop
--   an index a foreign key depends on.
--
-- Each is dropped and recreated under Prisma's own generated name, so a future
-- `migrate dev` does not propose to recreate it.
-- ---------------------------------------------------------------------------
DROP INDEX "clinical_master_items_organization_id_kind_code_key";
CREATE UNIQUE INDEX "clinical_master_items_organization_id_kind_code_key"
  ON "clinical_master_items" ("organization_id", "kind", "code") NULLS NOT DISTINCT;

DROP INDEX "clinical_master_codings_organization_id_item_id_system_code_key";
CREATE UNIQUE INDEX "clinical_master_codings_organization_id_item_id_system_code_key"
  ON "clinical_master_codings" ("organization_id", "item_id", "system", "code") NULLS NOT DISTINCT;

DROP INDEX "clinical_master_scopes_organization_id_item_id_specialty_id_key";
