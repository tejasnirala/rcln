-- ===========================================================================
-- CE-2 — consultation templates and their versions.
--
--   consultation_templates          the IDENTITY: "our dentistry consultation",
--                                   attached to a care context and optionally to
--                                   a node beneath it
--   consultation_template_versions  the DOCUMENT, and there are many
--
-- ⚠️ BOTH ARE PLATFORM-EXTENSIBLE, WITH `specialties`' POLICY AND NOT `files`'.
--   The platform ships a GENERAL consultation per care context so that a clinic
--   can consult on the day it opens; a clinic writes its own beside it and
--   overrides nothing. `files` permits a NULL organization_id in its WITH CHECK,
--   which is right for an asset the platform uploads on a tenant's behalf —
--   reproducing it here would let ANY CLINIC PUBLISH A PLATFORM-WIDE
--   CONSULTATION TEMPLATE, visible to every other tenant on the platform.
--
-- ⚠️ ONE MIGRATION, AND UNLIKE EVERY CE-1 MIGRATION IT NEEDS NO SPLIT.
--   `ConsultationTemplateStatus` is a BRAND-NEW type rather than an
--   `ALTER TYPE … ADD VALUE`, so the CHECK constraints below may name its
--   members in the same transaction that creates it. That is the whole reason
--   CD-9's enum trap does not apply here.
--
-- Generated by `prisma migrate diff`, then extended by hand. The hand-written
-- half starts where it says so.
-- ===========================================================================

