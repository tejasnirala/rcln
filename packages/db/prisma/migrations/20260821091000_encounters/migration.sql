-- ---------------------------------------------------------------------------
-- AT MOST ONE LIVE ENCOUNTER PER APPOINTMENT.
--
-- ⚠️ THE SECOND "START CONSULTATION" CLICK IS WHAT THIS REFUSES. Without it a
--   double submit — or two tabs, or a doctor and a resident on the same visit —
--   opens two records of one visit, and which one the prescription, the
--   invoice and the follow-up hang off is a race nobody can see afterwards.
--
-- AMENDED and CANCELLED rows are excluded because neither is live: an amendment
-- supersedes its original (CD-2), so the original and its correction cite the
-- same appointment on purpose, and exactly one of them is current.
--
-- Prisma cannot express a partial index, which is why this is here and not in
-- the model.
-- ---------------------------------------------------------------------------
CREATE UNIQUE INDEX "encounters_one_live_per_appointment"
  ON "encounters" ("organization_id", "appointment_id")
  WHERE "appointment_id" IS NOT NULL
    AND "deleted_at" IS NULL
    AND "status" IN ('DRAFT', 'FINALIZED');

-- ---------------------------------------------------------------------------
-- AT MOST ONE LIVE AMENDMENT PER AMENDED ENCOUNTER.
--
-- Two live corrections of one record is two versions of the truth with nothing
-- to choose between them. A CANCELLED amendment is excluded so that an
-- abandoned correction does not block a real one.
-- ---------------------------------------------------------------------------
CREATE UNIQUE INDEX "encounters_one_live_amendment"
  ON "encounters" ("organization_id", "amends_encounter_id")
  WHERE "amends_encounter_id" IS NOT NULL
    AND "deleted_at" IS NULL
    AND "status" <> 'CANCELLED';

-- ---------------------------------------------------------------------------
-- THE LIFECYCLE, AS THE DATABASE SEES IT.
--
-- ⚠️ A FINALIZED ROW WITH NO `finalized_at` IS THE BUG THIS REFUSES, and it is
--   what a half-written transaction leaves behind. The record would read as
--   signed in every screen and sort to the bottom of every date-ordered list.
--
-- DRAFT carries none of the finalization facts. FINALIZED and AMENDED carry all
-- of them — an AMENDED row was necessarily finalized first, because nothing
-- amends a draft; a draft is edited. CANCELLED carries a cancellation instead.
-- ---------------------------------------------------------------------------
ALTER TABLE "encounters"
  ADD CONSTRAINT "encounters_lifecycle_facts"
  CHECK (
    ("status" = 'DRAFT'
       AND "finalized_at" IS NULL AND "finalized_by" IS NULL
       AND "encounter_number" IS NULL
       AND "amended_at" IS NULL AND "cancelled_at" IS NULL)
    OR ("status" = 'FINALIZED'
       AND "finalized_at" IS NOT NULL AND "finalized_by" IS NOT NULL
       AND "encounter_number" IS NOT NULL
       AND "amended_at" IS NULL AND "cancelled_at" IS NULL)
    OR ("status" = 'AMENDED'
       AND "finalized_at" IS NOT NULL AND "finalized_by" IS NOT NULL
       AND "encounter_number" IS NOT NULL
       AND "amended_at" IS NOT NULL AND "cancelled_at" IS NULL)
    -- A consultation is cancelled from DRAFT and never from FINALIZED: a
    -- finalized record is corrected by an amendment, never withdrawn. So a
    -- CANCELLED row carries no finalization facts and burnt no number.
    OR ("status" = 'CANCELLED'
       AND "finalized_at" IS NULL AND "finalized_by" IS NULL
       AND "encounter_number" IS NULL
       AND "amended_at" IS NULL AND "cancelled_at" IS NOT NULL)
  );

-- An amendment says why. "The record changed and nobody said why" is the
-- failure an amendment trail exists to prevent.
ALTER TABLE "encounters"
  ADD CONSTRAINT "encounters_amendment_reason_present"
  CHECK (
    ("amends_encounter_id" IS NULL AND "amendment_reason" IS NULL)
    OR ("amends_encounter_id" IS NOT NULL AND "amendment_reason" IS NOT NULL)
  );

-- ⚠️ A DURATION OF "3" OF NOTHING IS NOT A DURATION. Value and unit travel
--   together or not at all; storing one without the other renders as a number
