-- ---------------------------------------------------------------------------
-- RLS — org + branch scoped, both loops, both tables.
--
-- ⚠️ `branch_id` IS NOT NULL ON BOTH, SO THE BRANCH POLICY IS ABSOLUTE — the
--   `branch_id IS NULL OR` half is dead code here, as it is for the invoice and
--   inventory tables. A doctor scoped to one site cannot read what another site
--   wrote about a patient, even by guessing a primary key.
--
--   That is the opposite call from `clinical_episodes`, and deliberately: the
--   JOURNEY follows the person across a hospital group (ADR-0016), the VISIT
--   belongs to the place it happened at.
--
-- The canonical copy of these policies is `prisma/rls/enable-rls.sql`; this is
-- the stanza for the two new tables, as the convention requires.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  t text;
  org_branch_scoped text[] := ARRAY[
    'encounters',
    'encounter_sections'
  ];
BEGIN
  FOREACH t IN ARRAY org_branch_scoped LOOP
    EXECUTE format('ALTER TABLE %I ENABLE   ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I NO FORCE ROW LEVEL SECURITY', t);

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
    EXECUTE format($f$
      CREATE POLICY tenant_isolation ON %I
        USING      (organization_id = app_current_org())
        WITH CHECK (organization_id = app_current_org())
    $f$, t);

    EXECUTE format('DROP POLICY IF EXISTS branch_isolation ON %I', t);
    EXECUTE format($f$
      CREATE POLICY branch_isolation ON %I AS RESTRICTIVE
        USING      (branch_id IS NULL OR branch_id = ANY (app_branch_scope()))
        WITH CHECK (branch_id IS NULL OR branch_id = ANY (app_branch_scope()))
    $f$, t);
  END LOOP;
END
$$;

-- ---------------------------------------------------------------------------
-- `encounters` CITES A TEMPLATE AND A VERSION THAT MAY BE PLATFORM ROWS, AND
-- NEITHER POINTER CAN BE COMPOSITE-FK'D.
--
-- ⚠️ THIS IS WHY THE COMPOSITE FK IS ABSENT, AND IT IS NOT AN OVERSIGHT. A
--   composite (organization_id, template_id) reference would make a PLATFORM
--   template uncitable: the encounter's organization_id is NOT NULL, so both
--   columns are non-null, so the FK would demand a template belonging to the
--   clinic — and the platform's GENERAL template is exactly what a doctor with
--   no classification resolves to. The constraint would refuse the most
--   ordinary consultation on the platform.
--
--   What replaces it is this RESTRICTIVE policy, the same shape
--   `specialty_visible` has on `consultation_templates` and `product_visible`
--   has on `batches`. Without it a clinic could cite ANOTHER TENANT'S private
--   template and read its name and its definition back out of the join.
-- ---------------------------------------------------------------------------
DROP POLICY IF EXISTS template_visible ON encounters;
CREATE POLICY template_visible ON encounters AS RESTRICTIVE
  USING (
    EXISTS (
      SELECT 1 FROM consultation_templates t
      WHERE t.id = encounters.template_id
        AND (t.organization_id IS NULL OR t.organization_id = app_current_org())
    )
    AND EXISTS (
      SELECT 1 FROM consultation_template_versions v
      WHERE v.id = encounters.template_version_id
        AND (v.organization_id IS NULL OR v.organization_id = app_current_org())
    )
  )
  WITH CHECK (
    EXISTS (
      SELECT 1 FROM consultation_templates t
      WHERE t.id = encounters.template_id
        AND (t.organization_id IS NULL OR t.organization_id = app_current_org())
    )
    AND EXISTS (
      SELECT 1 FROM consultation_template_versions v
      WHERE v.id = encounters.template_version_id
        AND (v.organization_id IS NULL OR v.organization_id = app_current_org())
    )
  );

