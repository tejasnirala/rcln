-- ---------------------------------------------------------------------------
-- TWO `item_id` COLUMNS ARE REQUIRED, AND PRISMA CANNOT SAY SO.
--
-- A required relation may not include a nullable scalar, and these relations
-- are plain FKs into a platform-extensible table. So the models declare them
-- optional and the database states the truth.
--
-- ⚠️ THE OTHER THREE — SYMPTOMS, DIAGNOSES, ADVICE — ARE GENUINELY NULLABLE,
--   and that is CD-6 and §6 rather than an inconsistency. A clinician must be
--   able to record a symptom the vocabulary has not learned yet, and forcing
--   every free-text entry to create a master row pollutes a SHARED PLATFORM
--   catalogue with one clinic's typos.
--
--   A PROCEDURE and an INVESTIGATION are different: they are billed, consumed
--   from stock (PI-9) and reported on, so a free-text one is a line nothing
--   downstream can price or count.
-- ---------------------------------------------------------------------------
ALTER TABLE "encounter_procedures" ALTER COLUMN "item_id" SET NOT NULL;
ALTER TABLE "encounter_investigations" ALTER COLUMN "item_id" SET NOT NULL;

-- ---------------------------------------------------------------------------
-- CODED OR TYPED, EXACTLY ONE.
--
-- ⚠️ `num_nonnulls(...) = 1` RATHER THAN "AT LEAST ONE". Allowing both would
--   let a custom label sit beside a coded word and silently contradict it —
--   and then every report grouping by `item_id` shows one thing while the
--   chart shows another. A row naming neither is a symptom of nothing.
-- ---------------------------------------------------------------------------
ALTER TABLE "encounter_symptoms"
  ADD CONSTRAINT "encounter_symptoms_coded_or_typed"
  CHECK (num_nonnulls("item_id", "custom_text") = 1);

ALTER TABLE "encounter_diagnoses"
  ADD CONSTRAINT "encounter_diagnoses_coded_or_typed"
  CHECK (num_nonnulls("item_id", "custom_text") = 1);

ALTER TABLE "encounter_advice"
  ADD CONSTRAINT "encounter_advice_coded_or_typed"
  CHECK (num_nonnulls("item_id", "custom_text") = 1);

-- ⚠️ A DURATION OF "3" OF NOTHING IS NOT A DURATION — the same pair rule
--   `encounters.chief_complaint_duration_*` carries, for the same reason.
ALTER TABLE "encounter_symptoms"
  ADD CONSTRAINT "encounter_symptoms_duration_pair"
  CHECK (
    ("duration_value" IS NULL AND "duration_unit" IS NULL)
    OR ("duration_value" IS NOT NULL AND "duration_unit" IS NOT NULL)
  );

ALTER TABLE "encounter_symptoms"
  ADD CONSTRAINT "encounter_symptoms_duration_positive"
  CHECK ("duration_value" IS NULL OR "duration_value" > 0);

-- ---------------------------------------------------------------------------
-- AT MOST ONE PRIMARY DIAGNOSIS PER CONSULTATION.
--
-- Two primaries is two answers to "what was this visit about", and every
-- report that groups by primary diagnosis counts the visit twice. Partial, and
-- therefore hand-written: Prisma cannot express `WHERE role = 'PRIMARY'`.
--
-- SECONDARY and DIFFERENTIAL are deliberately unconstrained — a consultation
-- legitimately carries several of each.
-- ---------------------------------------------------------------------------
CREATE UNIQUE INDEX "encounter_diagnoses_one_primary"
  ON "encounter_diagnoses" ("organization_id", "encounter_id")
  WHERE "role" = 'PRIMARY';

-- ---------------------------------------------------------------------------
-- THE DOSING PAIRS, AND THE ONE ORDERING RULE.
--
-- ⚠️ EVERY PAIR TRAVELS TOGETHER OR NOT AT ALL. "Twice per" nothing and "for
--   5" nothing are both prescriptions a pharmacist cannot fill, and both are
--   what a half-completed form produces.
-- ---------------------------------------------------------------------------
ALTER TABLE "encounter_prescriptions"
  ADD CONSTRAINT "encounter_prescriptions_frequency_pair"
  CHECK (
    ("frequency" IS NULL AND "frequency_unit" IS NULL)
    OR ("frequency" IS NOT NULL AND "frequency_unit" IS NOT NULL)
  );

ALTER TABLE "encounter_prescriptions"
  ADD CONSTRAINT "encounter_prescriptions_duration_pair"
  CHECK (
    ("duration_value" IS NULL AND "duration_unit" IS NULL)
    OR ("duration_value" IS NOT NULL AND "duration_unit" IS NOT NULL)
  );

ALTER TABLE "encounter_prescriptions"
  ADD CONSTRAINT "encounter_prescriptions_dose_pair"
  CHECK (
    ("dose" IS NULL AND "dose_unit" IS NULL)
    OR ("dose" IS NOT NULL AND "dose_unit" IS NOT NULL)
  );

-- ⚠️ POSITIVE, NOT NON-NEGATIVE. A dose of zero, a course of zero days and a
--   quantity of zero are each a form that was started and abandoned, and each
--   would print on a prescription as an instruction.
ALTER TABLE "encounter_prescriptions"
  ADD CONSTRAINT "encounter_prescriptions_amounts_positive"
  CHECK (
    ("dose" IS NULL OR "dose" > 0)
    AND ("quantity" IS NULL OR "quantity" > 0)
    AND ("frequency" IS NULL OR "frequency" > 0)
    AND ("duration_value" IS NULL OR "duration_value" > 0)
  );

-- A course that ends before it starts is a typo the database can catch.
ALTER TABLE "encounter_prescriptions"
  ADD CONSTRAINT "encounter_prescriptions_dates_ordered"
  CHECK ("start_date" IS NULL OR "end_date" IS NULL OR "end_date" >= "start_date");

-- ---------------------------------------------------------------------------
-- A REFERRAL NAMES SOMEBODY.
--
-- A specialty ("see a cardiologist"), a named colleague inside the
-- organization, or a clinician outside it — all three are ordinary, and a row
-- naming none of them is a referral to nobody.
-- ---------------------------------------------------------------------------
ALTER TABLE "encounter_referrals"
