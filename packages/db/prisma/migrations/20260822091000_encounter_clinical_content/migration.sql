-- RLS — org + branch scoped, both loops, all eight tables.
--
-- ⚠️ `branch_id` IS NOT NULL ON ALL EIGHT, SO THE BRANCH POLICY IS ABSOLUTE —
--   the `branch_id IS NULL OR` half is dead code here, as it is for
--   `encounters` and for the invoice and inventory tables. A doctor scoped to
--   one site cannot read what another site prescribed, concluded or ordered
--   for a patient, even by guessing a primary key.
--
-- The canonical copy of these policies is `prisma/rls/enable-rls.sql`; this is
-- the stanza for the eight new tables, as the convention requires.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  t text;
  org_branch_scoped text[] := ARRAY[
    'encounter_symptoms',
    'encounter_diagnoses',
    'encounter_procedures',
    'encounter_prescriptions',
    'encounter_investigations',
    'encounter_advice',
    'encounter_referrals',
    'encounter_attachments'
  ];
BEGIN
  FOREACH t IN ARRAY org_branch_scoped LOOP
    EXECUTE format('ALTER TABLE %I ENABLE   ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I NO FORCE ROW LEVEL SECURITY', t);

    EXECUTE format('DROP POLICY IF EXISTS tenant_isolation ON %I', t);
    EXECUTE format($f$
      CREATE POLICY tenant_isolation ON %I
        USING      (organization_id = app_current_org())
        WITH CHECK (organization_id = app_current_org())
    $f$, t);

    EXECUTE format('DROP POLICY IF EXISTS branch_isolation ON %I', t);
    EXECUTE format($f$
      CREATE POLICY branch_isolation ON %I AS RESTRICTIVE
        USING      (branch_id IS NULL OR branch_id = ANY (app_branch_scope()))
        WITH CHECK (branch_id IS NULL OR branch_id = ANY (app_branch_scope()))
    $f$, t);
  END LOOP;
END
$$;

-- ---------------------------------------------------------------------------
-- FIVE TABLES CITE A CLINICAL WORD THAT MAY BE A PLATFORM ROW.
--
-- ⚠️ THIS POLICY IS WHAT STANDS IN FOR THE COMPOSITE FK, WHICH IS IMPOSSIBLE
--   HERE — the same argument `template_visible` makes on `encounters`.
--   `clinical_master_items.organization_id` is nullable so that the platform
--   can ship a vocabulary every clinic sees; these rows' is NOT NULL, so a
--   composite reference would demand a word belonging to the clinic and refuse
--   every platform diagnosis on the platform.
--
--   Without this restriction a clinic could cite ANOTHER TENANT'S private word
--   and read its name and description back out of the join — which is a
--   competitor's clinical vocabulary, disclosed one selector at a time.
--
-- Written as a loop for the same reason the isolation policies are: five
-- identical stanzas differing only in a table name is five chances to fix a
-- bug in four places.
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  t text;
  cites_an_item text[] := ARRAY[
    'encounter_symptoms',
    'encounter_diagnoses',
    'encounter_procedures',
    'encounter_investigations',
    'encounter_advice'
  ];
BEGIN
  FOREACH t IN ARRAY cites_an_item LOOP
    EXECUTE format('DROP POLICY IF EXISTS item_visible ON %I', t);
    -- ⚠️ `item_id IS NULL OR …` because three of the five allow a typed entry
    --    with no coded word at all. On the two where the column is NOT NULL the
    --    left half is dead code, which is the same shape `designation_visible`
    --    has on `invitations`.
    EXECUTE format($f$
      CREATE POLICY item_visible ON %I AS RESTRICTIVE
        USING (item_id IS NULL OR EXISTS (
          SELECT 1 FROM clinical_master_items i
          WHERE i.id = %I.item_id
            AND (i.organization_id IS NULL OR i.organization_id = app_current_org())
        ))
        WITH CHECK (item_id IS NULL OR EXISTS (
          SELECT 1 FROM clinical_master_items i
          WHERE i.id = %I.item_id
            AND (i.organization_id IS NULL OR i.organization_id = app_current_org())
        ))
    $f$, t, t, t);
  END LOOP;
END
$$;

-- ---------------------------------------------------------------------------
-- A PRESCRIPTION CITES A PRODUCT THAT MAY BE A PLATFORM ROW.
--
-- Exactly the shape `batches` has, and named the same. `NEXT_SESSION.md` item
-- 1 predicted this table would need it, and it does: without it a clinic
-- prescribes against another tenant's private product and reads its name,
-- strength and pack size back out of the join.
-- ---------------------------------------------------------------------------
DROP POLICY IF EXISTS product_visible ON encounter_prescriptions;
CREATE POLICY product_visible ON encounter_prescriptions AS RESTRICTIVE
  USING (EXISTS (
    SELECT 1 FROM products p
    WHERE p.id = encounter_prescriptions.product_id
      AND (p.organization_id IS NULL OR p.organization_id = app_current_org())
  ))
  WITH CHECK (EXISTS (
    SELECT 1 FROM products p
    WHERE p.id = encounter_prescriptions.product_id
      AND (p.organization_id IS NULL OR p.organization_id = app_current_org())
  ));

-- ---------------------------------------------------------------------------
-- A REFERRAL CITES A SPECIALTY THAT MAY BE A PLATFORM ROW.
--
-- Nullable — a referral to a named colleague or to somebody outside the
-- organization names no specialty at all — so NULL is permitted, as it is on
-- `clinical_episodes.primary_specialty_id`.
--
-- ⚠️ `doctor_profile_id` NEEDS NO POLICY, and that is not an omission. A doctor
--   profile is always org-scoped, so the composite FK CAN be drawn there and
--   is — which is the whole reason these `*_visible` policies exist only where
--   it cannot.
-- ---------------------------------------------------------------------------
DROP POLICY IF EXISTS specialty_visible ON encounter_referrals;
CREATE POLICY specialty_visible ON encounter_referrals AS RESTRICTIVE
  USING (specialty_id IS NULL OR EXISTS (
    SELECT 1 FROM specialties s
    WHERE s.id = encounter_referrals.specialty_id
      AND (s.organization_id IS NULL OR s.organization_id = app_current_org())
  ))
  WITH CHECK (specialty_id IS NULL OR EXISTS (
    SELECT 1 FROM specialties s
    WHERE s.id = encounter_referrals.specialty_id
      AND (s.organization_id IS NULL OR s.organization_id = app_current_org())
  ));

-- ---------------------------------------------------------------------------
-- Grants. Ordinary CRUD.
--
-- ⚠️ DELETE IS GRANTED AND IS THE ORDINARY WAY A ROW LEAVES A DRAFT — none of
--   these tables has a `deleted_at`, deliberately. A diagnosis the clinician
--   typed and then removed before signing is a correction to something that
--   was never a record; keeping a tombstone of it would make the chart's
--   history noisier without making it truer. Immutability begins at
--   FINALIZED, and it is `assertDraft` on the parent encounter that enforces
--   it — an amendment COPIES these rows onto a new encounter rather than
--   moving them, so both signed records stay whole.
-- ---------------------------------------------------------------------------
GRANT SELECT, INSERT, UPDATE, DELETE ON
  "encounter_symptoms",
  "encounter_diagnoses",
  "encounter_procedures",
  "encounter_prescriptions",
  "encounter_investigations",
  "encounter_advice",
  "encounter_referrals",
  "encounter_attachments"
TO rcln_app;
